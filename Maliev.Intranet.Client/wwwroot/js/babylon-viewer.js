/**
 * BabylonJS 3D Viewer for Maliev Intranet
 * Lazy-loads BabylonJS from CDN and provides functions for Blazor JS interop.
 *
 * Supported formats (via babylonjs.loaders): .glb, .gltf, .stl, .obj
 * Unsupported formats (.step, .iges, .3mf etc.) must be converted to GLB before reaching this script.
 *
 * COORDINATE SYSTEM CONTRACT:
 *   All GLBs served to this viewer follow the glTF spec: Y-up, mm.
 *   The viewer applies a +90° X rotation at load time to display in Z-up (CAD standard):
 *     X = right, Y = depth (into screen from front), Z = up
 *   This matches the preview images generated by GeometryService (pyvista, viewup=(0,0,1)).
 */

